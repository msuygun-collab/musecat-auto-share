def normalize_lang(lang: str | None) -> str:
    """Normalize a language code to 'tr' or 'en' (defaults to 'tr')."""
    code = (lang or "tr").strip().lower()
    if code.startswith("en"):
        return "en"
    return "tr"


def tr(key: str, lang: str = "tr", **kwargs: Any) -> str:
    """Translate a message key into the requested language with safe formatting."""
    norm = normalize_lang(lang)
    table = TRANSLATIONS.get(norm, TRANSLATIONS["tr"])
    text = table.get(key)
    if text is None:
        text = TRANSLATIONS["tr"].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text
