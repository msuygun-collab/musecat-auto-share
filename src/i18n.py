def normalize_lang(lang: str | None) -> str:
    """Normalize a language code to one of the 13 supported codes.

    Defaults to 'tr' when empty/None, and falls back to 'en' for unknown codes.
    """
    if lang is None or not str(lang).strip():
        return "tr"
    code = str(lang).strip().lower()
    if code in SUPPORTED_LANGUAGES:
        return code
    base = code.replace("_", "-").split("-", 1)[0]
    if base in SUPPORTED_LANGUAGES:
        return base
    return "en"


def tr(key: str, lang: str = "tr", **kwargs: Any) -> str:
    """Translate a message key into the requested language with safe fallback to English."""
    norm = normalize_lang(lang)
    table = TRANSLATIONS.get(norm, TRANSLATIONS["en"])
    text = table.get(key)
    if text is None:
        text = TRANSLATIONS["en"].get(key)
    if text is None:
        text = TRANSLATIONS["tr"].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text
